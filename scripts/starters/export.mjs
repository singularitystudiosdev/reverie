// Writes src/data/starters.generated.ts: the 100 starter personas as the app's
// built-in roster entries, read from their server/personas/<id>.md files (the
// single source of truth), with only the assets each persona actually has on
// disk: profile still (+ small), profile video loop, background (+ small).
// Avatar crops come from .tmp/starters-raw/faces.json when the face pass ran.
//   node scripts/starters/export.mjs
import fs from 'node:fs';
import path from 'node:path';
import { getSection, parsePersona } from '../../server/src/personas/markdown.ts';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const roster = JSON.parse(fs.readFileSync(path.join(root, 'server/starters/roster.json'), 'utf8')).personas;
const facesFile = path.join(root, '.tmp/starters-raw/faces.json');
const faces = fs.existsSync(facesFile) ? JSON.parse(fs.readFileSync(facesFile, 'utf8')) : {};
const has = (f) => fs.existsSync(path.join(root, 'public/characters', f));

// Deal the local deck order round-robin across kinds so it never runs ten anime cards in a row.
const buckets = { anime: [], realistic: [], men: [], other: [], novel: [] };
for (const p of roster) {
  const b = p.group === 'novel' ? 'novel' : p.gender === 'male' ? 'men' : p.style === 'Anime' ? 'anime' : p.style === 'Realistic' ? 'realistic' : 'other';
  buckets[b].push(p);
}
const order = [];
const pattern = ['anime', 'realistic', 'novel', 'anime', 'men', 'realistic', 'novel', 'other'];
while (order.length < roster.length) {
  for (const b of pattern) if (buckets[b].length) order.push(buckets[b].shift());
}

const seeds = [];
const missing = [];
for (const r of order) {
  const file = path.join(root, 'server/personas', `${r.id}.md`);
  if (!fs.existsSync(file) || !has(`${r.id}.webp`)) {
    missing.push(r.id);
    continue;
  }
  const p = parsePersona(fs.readFileSync(file, 'utf8'));
  // A hand-set crop in the roster wins over the face pass (non-human faces Vision misses).
  const crop = r.avatar ?? faces[r.id];
  seeds.push({
    id: p.meta.id,
    name: p.meta.name,
    kind: p.meta.kind,
    style: p.meta.style,
    theme: p.meta.theme,
    tagline: p.meta.tagline,
    bio: getSection(p, 'Bio')?.body ?? p.intro,
    opener: getSection(p, 'Opener')?.body ?? '',
    loop: has(`${r.id}-loop.mp4`),
    scene: has(`${r.id}-scene.webp`) && has(`${r.id}-scene-sm.webp`),
    ...(crop ? { avatarPosition: crop.position, avatarScale: crop.scale } : {}),
  });
}

const out = `// Generated by scripts/starters/export.mjs from server/personas/<id>.md. Do not edit by hand.
// ${seeds.length} starter personas: profile still, profile video loop and background only.
import type { StarterSeed } from './characters';

export const starterSeeds: StarterSeed[] = ${JSON.stringify(seeds, null, 2)};
`;
fs.writeFileSync(path.join(root, 'src/data/starters.generated.ts'), out);
console.log(`wrote ${seeds.length} starters (${seeds.filter((s) => s.loop).length} with a profile video, ${seeds.filter((s) => s.scene).length} with a background)`);
if (missing.length) console.log(`skipped (no persona file or no still yet): ${missing.join(', ')}`);
